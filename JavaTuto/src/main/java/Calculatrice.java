public class Calculatrice {

    public int multiplier(int a, int b){
        return a*b;
    }

    public double diviser(double a, double b){
        return a/b;
    }

    public int additionner(int a, int b){
        return a+b;
    }

    public int soustraire(int a, int b){
        return a-b;
    }
}

